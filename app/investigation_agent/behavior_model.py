"""
Replayable Application Behavior Model.
Encapsulates discovered state classes, verified transitions, invariants, and user journeys.
Provides executable export of discovered user journeys to clean sync Playwright Python code.
"""

from typing import Dict, List, Any, Optional
from pydantic import BaseModel, Field

from app.investigation_agent.models import BugLead, StateTransitionRecord


class ApplicationBehaviorModel(BaseModel):
    """
    Formal behavior intelligence model of the investigated application.
    """
    state_classes: Dict[str, Dict[str, Any]] = Field(default_factory=dict)
    verified_transitions: List[Dict[str, Any]] = Field(default_factory=list)
    discovered_invariants: List[Dict[str, Any]] = Field(default_factory=list)
    discovered_journeys: List[Dict[str, Any]] = Field(default_factory=list)
    confirmed_bug_leads: List[BugLead] = Field(default_factory=list)

    def add_state_class(
        self,
        class_id: str,
        primary_purpose: str,
        representative_route: str,
        key_controls: List[str],
        outbound_transitions: List[str],
    ):
        self.state_classes[class_id] = {
            "id": class_id,
            "class_id": class_id,
            "primary_purpose": primary_purpose,
            "representative_route": representative_route,
            "key_controls": key_controls[:10],
            "outbound_transitions": outbound_transitions[:10],
        }

    def add_transition(
        self,
        source_class: str,
        target_class: str,
        trigger_action: str,
        expected_outcome: str,
    ):
        self.verified_transitions.append({
            "source_class": source_class,
            "target_class": target_class,
            "trigger_action": trigger_action,
            "expected_outcome": expected_outcome,
        })

    def add_journey(self, name: str, steps: List[Dict[str, Any]]):
        self.discovered_journeys.append({
            "name": name,
            "steps": steps,
        })

    def export_playwright_test(self, journey_name: Optional[str] = None) -> str:
        """
        Exports a self-contained, executable sync Playwright Python test script
        representing the selected or first discovered user journey.
        """
        journey = None
        if journey_name:
            journey = next((j for j in self.discovered_journeys if j["name"] == journey_name), None)
        if not journey and self.discovered_journeys:
            journey = self.discovered_journeys[0]

        if not journey:
            return "# No discovered journeys available for export."

        code_lines = [
            "# Auto-generated by VerityQA Autonomous Investigation Agent",
            "# Replayable Application Journey Test",
            "import pytest",
            "from playwright.sync_api import sync_playwright, expect",
            "",
            f"def test_{journey['name'].lower().replace(' ', '_').replace('-', '_')}():",
            '    """',
            f'    Test Objective: Replay and verify the discovered application journey "{journey["name"]}".',
            "    Preconditions: Application server is online and reachable.",
            "    Evidence Grounding: Derived directly from empirical DOM observations and state transitions.",
            '    """',
            "    with sync_playwright() as p:",
            "        browser = p.chromium.launch(headless=True)",
            "        context = browser.new_context()",
            "        page = context.new_page()",
            "",
        ]

        step_idx = 0
        for step in journey.get("steps", []):
            step_idx += 1
            action = step.get("action", "NAVIGATE")
            target = step.get("target", "")
            val = step.get("value", "")
            desc = step.get("description", f"Execute {action}")
            exp_url = step.get("expected_url_fragment", "")
            exp_sel = step.get("expected_selector", "")
            exp_hdg = step.get("expected_heading", "")
            ev_refs = step.get("evidence_refs", [])
            ev_comment = f" [Evidence: {', '.join(ev_refs)}]" if ev_refs else ""
            act = str(action).upper()

            code_lines.append(f"        # Step {step_idx}: {desc}{ev_comment}")
            if any(k in act for k in ("NAVIGATE", "GOTO")):
                code_lines.append(f"        page.goto({repr(target)}, wait_until='domcontentloaded')")
            elif any(k in act for k in ("FILL", "TYPE")):
                if val == "${CREDENTIAL_PASSWORD}":
                    # Never write a credential into an exported script.
                    code_lines.append(f"        page.locator({repr(target)}).fill(__import__('os').environ['VERITYQA_TEST_PASSWORD'])")
                else:
                    code_lines.append(f"        page.locator({repr(target)}).fill({repr(val)})")
            elif any(k in act for k in ("CLICK", "SUBMIT")):
                code_lines.append(f"        page.locator({repr(target)}).click()")
                code_lines.append("        page.wait_for_timeout(400)")
            elif "UNCHECK" in act:
                code_lines.append(f"        page.locator({repr(target)}).uncheck()")
            elif "CHECK" in act:
                code_lines.append(f"        page.locator({repr(target)}).check()")
            elif "SELECT" in act:
                code_lines.append(f"        page.locator({repr(target)}).select_option({repr(val)})")

            if exp_url:
                code_lines.append(f"        assert {repr(exp_url)} in page.url, f'Expected {exp_url} in URL, got {{page.url}}'")
            if exp_hdg:
                clean_hdg = exp_hdg.strip()
                if clean_hdg and len(clean_hdg) > 2:
                    code_lines.append(f"        assert {repr(clean_hdg)} in page.locator('body').inner_text(), f'Expected heading/landmark {clean_hdg}'")
            if exp_sel:
                code_lines.append(f"        assert page.locator({repr(exp_sel)}).count() > 0")

        code_lines.extend([
            "",
            "        # Verify final application state and DOM integrity",
            "        assert page.url is not None and page.url.startswith('http')",
            "        assert len(page.locator('body').inner_text().strip()) > 0",
            "        browser.close()",
            "",
            "if __name__ == '__main__':",
            f"    test_{journey['name'].lower().replace(' ', '_').replace('-', '_')}()",
            "    print('Journey replay completed successfully.')",
        ])

        return "\n".join(code_lines)
