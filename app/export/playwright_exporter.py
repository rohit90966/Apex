import re
from typing import List
from app.schemas import TestCase, ActionStep, ActionType, AssertionType
from app.execution.runner import QAPlanRunner


class PlaywrightTestExporter:
    """
    Exports executable test journeys into clean, self-contained Python Playwright scripts
    ready to run directly in CI/CD pipelines via `pytest` or `python -m unittest`.
    """

    def __init__(self, runner: QAPlanRunner = None):
        self.runner = runner or QAPlanRunner()

    def export_to_python_script(self, test_cases: List[TestCase], target_url: str) -> str:
        """
        Generates a standalone, runnable Python script using Playwright sync or async API.
        """
        lines = [
            '"""',
            'Automated Regression Test Suite generated by VerityQA Autonomous AI QA Engineer.',
            f'Target Application: {target_url}',
            'Requirements: pip install playwright pytest-playwright pytest',
            'Run via: pytest -v <this_file.py>',
            '"""',
            'import pytest',
            'from playwright.sync_api import Page, expect',
            '',
            '',
        ]

        for idx, tc in enumerate(test_cases, 1):
            safe_name = re.sub(r'[^a-zA-Z0-9_]', '_', tc.name).lower().strip('_')
            func_name = f"test_{safe_name}_{idx}"
            steps = self.runner.synthesize_steps(tc, target_url)

            lines.append(f"def {func_name}(page: Page):")
            lines.append(f'    """')
            lines.append(f'    Test ID: {tc.test_id}')
            lines.append(f'    Objective: {tc.objective}')
            lines.append(f'    Expected: {tc.expected_outcome}')
            lines.append(f'    """')

            for s in steps:
                lines.append(f"    # Step {s.step_number}: {s.description}")
                if s.action == ActionType.NAVIGATE:
                    lines.append(f'    page.goto("{s.value}")')
                elif s.action == ActionType.FILL:
                    val = (s.value or "").replace('"', '\\"')
                    lines.append(f'    page.locator("{s.selector}").first.fill("{val}")')
                elif s.action == ActionType.CLICK:
                    lines.append(f'    page.locator("{s.selector}").first.click()')
                elif s.action == ActionType.SELECT:
                    lines.append(f'    page.locator("{s.selector}").first.select_option("{s.value}")')
                elif s.action == ActionType.WAIT_FOR_ELEMENT:
                    lines.append(f'    page.locator("{s.selector}").first.wait_for(state="visible")')
                elif s.action == ActionType.EVAL_JS:
                    js_val = (s.value or "").replace('"', '\\"')
                    lines.append(f'    page.evaluate("{js_val}")')

                # Assertions
                if s.assertion:
                    atype = s.assertion.assertion_type
                    exp = (s.assertion.expected_value or "").replace('"', '\\"')
                    if atype == AssertionType.TEXT_VISIBLE:
                        if s.assertion.target_selector:
                            lines.append(f'    expect(page.locator("{s.assertion.target_selector}").first).to_contain_text("{exp}")')
                        else:
                            lines.append(f'    expect(page.locator("body")).to_contain_text("{exp}")')
                    elif atype == AssertionType.TEXT_NOT_VISIBLE:
                        lines.append(f'    expect(page.locator("body")).not_to_contain_text("{exp}")')
                    elif atype == AssertionType.URL_CONTAINS:
                        lines.append(f'    expect(page).to_have_url(re.compile(r".*{exp}.*"))')
                    elif atype == AssertionType.ELEMENT_VISIBLE:
                        lines.append(f'    expect(page.locator("{s.assertion.target_selector}").first).to_be_visible()')
                    elif atype == AssertionType.ELEMENT_DISABLED:
                        lines.append(f'    expect(page.locator("{s.assertion.target_selector}").first).to_be_disabled()')

            lines.append("")
            lines.append("")

        return "\n".join(lines)
